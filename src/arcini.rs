//! Converts FreeArc arc.ini `[External compressor:...]` sections into codecs.toml.
//! Semantics follow FreeArc 0.67 Compression/External/C_External.cpp:
//!   - section header "[External compressor:a, b, c]" defines each name separately;
//!   - keys: mem/cmem/dmem/solid (compression-only, ignored here), packcmd (ignored),
//!     unpackcmd, datafile, packedfile, default, header;
//!   - "{compressor}" is replaced by the method name;
//!   - " <stdin>" / " <stdout>" switch that side to a pipe, otherwise the literal file names
//!     `packedfile` (input) / `datafile` (output) are used inside a temp folder;
//!   - a `cls-<name>.dll` next to arc.ini takes precedence over arc.ini's section for <name>.

use anyhow::Result;
use std::fmt::Write as _;
use std::path::Path;

#[derive(Debug, PartialEq)]
pub struct Section {
    pub name: String,
    pub unpackcmd: String,
    pub datafile: String,
    pub packedfile: String,
    pub default: String,
    pub header: bool,
}

pub fn parse(text: &str) -> (Vec<Section>, Vec<String>) {
    let text = format!("\n{}", text.replace("\r\n", "\n"));
    let mut out = Vec::new();
    let mut warnings = Vec::new();
    for raw in text.split("\n[").skip(1) {
        let mut lines = raw.lines();
        let head = format!("[{}", lines.next().unwrap_or_default().trim_end());
        let Some(names) = head.strip_prefix("[External compressor:").and_then(|h| h.strip_suffix(']')) else { continue };
        let names: Vec<String> = names.split(',').map(|n| n.trim().to_string()).filter(|n| !n.is_empty()).collect();
        let mut kv: Vec<(String, String)> = Vec::new();
        for line in lines {
            if line.trim().is_empty() || line.starts_with(';') {
                continue;
            }
            match line.split_once('=') {
                Some((k, v)) => kv.push((k.trim().to_ascii_lowercase(), v.trim().to_string())),
                None => warnings.push(format!("{head}: ignoring line without '=': {line}")),
            }
        }
        for name in names {
            let get = |key: &str| kv.iter().rev().find(|(k, _)| k == key).map(|(_, v)| v.replace("{compressor}", &name));
            out.push(Section {
                unpackcmd: get("unpackcmd").unwrap_or_default(),
                datafile: get("datafile").unwrap_or_else(|| "$$arcdatafile$$.tmp".into()),
                packedfile: get("packedfile").unwrap_or_else(|| "$$arcpackedfile$$.tmp".into()),
                default: get("default").unwrap_or_default(),
                header: get("header").map(|v| v.trim() != "0").unwrap_or(true),
                name,
            });
        }
    }
    (out, warnings)
}

/// Translates one section's unpackcmd into our cmd syntax.
pub fn translate_cmd(s: &Section) -> String {
    let stdin = s.unpackcmd.contains(" <stdin>");
    let stdout = s.unpackcmd.contains(" <stdout>");
    let mut cmd = s.unpackcmd.replacen(" <stdin>", "", 1).replacen(" <stdout>", "", 1);
    // A file name's extension matters to some codecs (mpz.exe writes "$$arcdatafile$$.mp3"):
    // anything but FreeArc's default ".tmp" is kept, and the temp file gets it too.
    let placeholder = |file: &str, base: &str, ph: &str| match file.strip_prefix(base) {
        Some(ext) if !ext.is_empty() && !ext.eq_ignore_ascii_case(".tmp") => format!("{ph}{ext}"),
        _ => ph.to_string(),
    };
    if !stdin {
        cmd = cmd.replace(&s.packedfile, &placeholder(&s.packedfile, "$$arcpackedfile$$", "{input}"));
    }
    if !stdout {
        cmd = cmd.replace(&s.datafile, &placeholder(&s.datafile, "$$arcdatafile$$", "{output}"));
    }
    cmd
}

fn toml_str(s: &str) -> String {
    if !s.contains('\'') && !s.contains('\n') {
        format!("'{s}'")
    } else {
        format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
    }
}

pub fn to_toml(arc_ini: &Path) -> Result<String> {
    let text = std::fs::read(arc_ini)?;
    let text = String::from_utf8_lossy(&text);
    let (sections, warnings) = parse(&text);
    let dir = arc_ini.parent().unwrap_or(Path::new("."));
    let mut t = String::new();
    writeln!(t, "# Generated by `arc-unpack import-arcini` from {}", arc_ini.display())?;
    for w in &warnings {
        writeln!(t, "# warning: {w}")?;
    }
    writeln!(t, "codec_dir = {}", toml_str(&std::path::absolute(dir)?.to_string_lossy()))?;
    if dir.join("unarc.dll").is_file() {
        writeln!(t, "# Archives using FreeArc built-ins (delta, dispack, 4x4, tor, ...) go through this whole:")?;
        writeln!(t, "unarc = 'unarc.dll'")?;
    }
    let mut cls: Vec<String> = std::fs::read_dir(dir)?
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().to_ascii_lowercase())
        .filter(|n| n.starts_with("cls-") && n.ends_with(".dll"))
        .collect();
    cls.sort();
    if !cls.is_empty() {
        writeln!(t, "\n# CLS codecs found in codec_dir (used automatically, no entry needed):")?;
        for c in &cls {
            writeln!(t, "#   {} -> method \"{}\"", c, &c[4..c.len() - 4])?;
        }
    }
    let mut seen = std::collections::HashSet::new();
    for s in &sections {
        if !seen.insert(s.name.clone()) {
            // FreeArc searches its method table in order, so the first definition wins.
            writeln!(t, "\n# '{}' is defined again later in arc.ini; FreeArc uses the first definition", s.name)?;
            continue;
        }
        // Repack arc.ini files are often shared templates. When the installer ships
        // cls-<name>.dll, FreeArc decodes the method with it, whatever arc.ini says (a missing
        // program, or no unpackcmd at all).
        if cls.iter().any(|c| c[4..c.len() - 4] == s.name.to_ascii_lowercase()) {
            writeln!(t, "\n# '{}' is also in arc.ini, but cls-{}.dll decodes it, as in FreeArc", s.name, s.name.to_ascii_lowercase())?;
            continue;
        }
        writeln!(t, "\n[methods.{}]", toml_str(&s.name))?;
        if s.unpackcmd.trim().is_empty() {
            writeln!(t, "# arc.ini has no unpackcmd: FreeArc passes the data through unchanged")?;
            if s.header {
                writeln!(t, "# NOTE: header=1 with no command is not handled exactly (flag byte is kept)")?;
            }
            writeln!(t, "alias = 'storing'")?;
            continue;
        }
        writeln!(t, "# unpackcmd = {}", s.unpackcmd)?;
        writeln!(t, "cmd = {}", toml_str(&translate_cmd(s)))?;
        if !s.header {
            writeln!(t, "header = false")?;
        }
        if !s.default.is_empty() {
            writeln!(t, "default = {}", toml_str(&s.default))?;
        }
    }
    Ok(t)
}

#[cfg(test)]
mod tests {
    use super::*;

    const INI: &str = "[Common]\r\nfoo=bar\r\n\r\n[External compressor:ccm123, ccmx123]\r\nmem = 276\r\n; comment\r\npackcmd   = {compressor} c $$arcdatafile$$.tmp $$arcpackedfile$$.tmp\r\nunpackcmd = {compressor} d $$arcpackedfile$$.tmp $$arcdatafile$$.tmp\r\n\r\n[External compressor:srep]\r\nheader = 0\r\npackcmd = srep {options} - - <stdin> <stdout>\r\nunpackcmd = srep -d {options}- - <stdin> <stdout>\r\n\r\n[External compressor:tempfile]\r\nheader=0\r\n";

    #[test]
    fn parses_sections() {
        let (s, w) = parse(INI);
        assert!(w.is_empty(), "{w:?}");
        assert_eq!(s.len(), 4);
        assert_eq!(s[0].name, "ccm123");
        assert_eq!(s[1].name, "ccmx123");
        assert_eq!(s[1].unpackcmd, "ccmx123 d $$arcpackedfile$$.tmp $$arcdatafile$$.tmp");
        assert!(s[0].header);
        assert!(!s[2].header);
        assert_eq!(translate_cmd(&s[0]), "ccm123 d {input} {output}");
        // Extensions other than .tmp stay: mpz.exe decides by them.
        let mpz = Section {
            name: "mpz".into(),
            unpackcmd: "mpz.exe d $$arcpackedfile$$.mpz $$arcdatafile$$.mp3".into(),
            packedfile: "$$arcpackedfile$$.mpz".into(),
            datafile: "$$arcdatafile$$.mp3".into(),
            default: String::new(),
            header: false,
        };
        assert_eq!(translate_cmd(&mpz), "mpz.exe d {input}.mpz {output}.mp3");
        assert_eq!(translate_cmd(&s[2]), "srep -d {options}- -");
        assert_eq!(s[3].unpackcmd, "");
    }

    #[test]
    fn translated_config_resolves() {
        let (s, _) = parse(INI);
        let mut toml_text = String::new();
        for sec in &s[..3] {
            toml_text += &format!("[methods.{}]\ncmd = {}\nheader = {}\n", sec.name, toml_str(&translate_cmd(sec)), sec.header);
        }
        let cfg: crate::config::Config = toml::from_str(&toml_text).unwrap();
        let st = cfg.resolve("srep:m3yf").unwrap();
        match &st[0].codec {
            crate::config::Codec::External(e) => {
                assert_eq!(e.argv, vec!["srep", "-d", "-m3yf", "-", "-"]);
                assert!(!e.input_file && !e.output_file && !e.header);
            }
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn cls_dll_takes_precedence_over_arc_ini() {
        let dir = std::env::temp_dir().join(format!("arc-unpack-arcini-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        // A template arc.ini: one method with a program the installer doesn't ship, one with no
        // unpackcmd; the installer ships CLS DLLs for both (any letter case).
        let ini = "[External compressor:mpzz]\r\nheader = 0\r\nunpackcmd = oggre_dec.exe {options} $$arcpackedfile$$.tmp $$arcdatafile$$.tmp\r\n\r\n[External compressor:msc]\r\nheader = 0\r\npackcmd = msc c -v {options} $$arcdatafile$$.tmp $$arcpackedfile$$.tmp\r\n\r\n[External compressor:rzs]\r\nheader = 0\r\nunpackcmd = rz.exe d - - <stdin> <stdout>\r\n";
        std::fs::write(dir.join("arc.ini"), ini).unwrap();
        std::fs::write(dir.join("cls-mpzz.dll"), b"").unwrap();
        std::fs::write(dir.join("CLS-MSC.dll"), b"").unwrap();
        let toml_text = to_toml(&dir.join("arc.ini")).unwrap();
        let cfg: crate::config::Config = toml::from_str(&toml_text).unwrap();
        for m in ["mpzz", "msc:raw=0:tak=9"] {
            let st = cfg.resolve(m).unwrap();
            assert!(matches!(&st[0].codec, crate::config::Codec::Cls { .. }), "{m}: {:?}", st[0].codec);
        }
        // Methods without a DLL still come from arc.ini.
        assert!(matches!(&cfg.resolve("rzs").unwrap()[0].codec, crate::config::Codec::External(_)));
        let _ = std::fs::remove_dir_all(&dir);
    }
}
